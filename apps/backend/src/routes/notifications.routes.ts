import { z } from 'zod';
import type { FastifyPluginAsyncZod } from '@fastify/type-provider-zod';
import { pushPlatform } from '../db/schema.js';
import { errorResponseSchema } from '../lib/errors.js';
import {
  notificationDtoSchema,
  notificationPreferencesSchema,
  toNotificationDto,
  updateNotificationPreferencesSchema,
} from '../lib/notification-serializers.js';
import { pageQuerySchema, parsePage } from '../lib/pagination.js';
import {
  countUnreadNotifications,
  getNotificationPreferences,
  listNotifications,
  markAllNotificationsRead,
  markNotificationRead,
  updateNotificationPreferences,
} from '../services/notification.service.js';
import { registerPushDevice, unregisterPushDevice } from '../services/push-device.service.js';

const listQuerySchema = pageQuerySchema.extend({
  unreadOnly: z
    .enum(['true', 'false'])
    .optional()
    .describe('Only unread notifications when "true"'),
});

const notificationParamsSchema = z.object({ id: z.uuid() });

const installationIdSchema = z
  .string()
  .trim()
  .min(1)
  .max(200)
  .describe('Stable per-installation identifier generated by the app');

const registerDeviceSchema = z
  .strictObject({
    installationId: installationIdSchema,
    expoToken: z
      .string()
      .max(1024)
      .describe('ExponentPushToken[...]; malformed tokens get 400 INVALID_PUSH_TOKEN'),
    platform: z.enum(pushPlatform.enumValues),
  })
  .meta({ id: 'RegisterPushDeviceRequest' });

const unreadCountSchema = z.object({ count: z.int().min(0) }).meta({ id: 'UnreadCount' });

// Clients may PUT/POST with no body at all, which Fastify hands over as null.
const emptyBodySchema = z.object({}).nullish();

const security = [{ bearerAuth: [] }];

export const notificationRoutes: FastifyPluginAsyncZod = async (app) => {
  app.addHook('onRequest', app.authenticate);

  app.get(
    '/notifications',
    {
      schema: {
        tags: ['notifications'],
        summary: 'Inbox of the authenticated user, newest first',
        description:
          'Paginated with zero-based page (default 0) and pageSize (default 20, max 100). ' +
          'Every notification is recorded regardless of push preferences.',
        security,
        querystring: listQuerySchema,
        response: {
          200: z.array(notificationDtoSchema),
          400: errorResponseSchema,
          401: errorResponseSchema,
        },
      },
    },
    async (request) => {
      const { unreadOnly, ...page } = request.query;
      const views = await listNotifications(
        app.db,
        request.user.id,
        { unreadOnly: unreadOnly === 'true' },
        parsePage(page),
      );
      return views.map(toNotificationDto);
    },
  );

  app.get(
    '/notifications/unread-count',
    {
      schema: {
        tags: ['notifications'],
        summary: 'Number of unread notifications of the authenticated user',
        security,
        response: { 200: unreadCountSchema, 401: errorResponseSchema },
      },
    },
    async (request) => ({ count: await countUnreadNotifications(app.db, request.user.id) }),
  );

  app.put(
    '/notifications/:id/read',
    {
      schema: {
        tags: ['notifications'],
        summary: 'Mark one of your notifications read (idempotent)',
        description: "Another user's notification answers 404 NOTIFICATION_NOT_FOUND.",
        security,
        params: notificationParamsSchema,
        body: emptyBodySchema,
        response: {
          200: notificationDtoSchema,
          400: errorResponseSchema,
          401: errorResponseSchema,
          404: errorResponseSchema,
        },
      },
    },
    async (request) =>
      toNotificationDto(
        await markNotificationRead(app.db, request.user.id, request.params.id, app.clock()),
      ),
  );

  app.post(
    '/notifications/read-all',
    {
      schema: {
        tags: ['notifications'],
        summary: 'Mark every notification of the authenticated user read',
        security,
        body: emptyBodySchema,
        response: {
          204: z.null().describe('All read'),
          400: errorResponseSchema,
          401: errorResponseSchema,
        },
      },
    },
    async (request, reply) => {
      await markAllNotificationsRead(app.db, request.user.id, app.clock());
      return reply.code(204).send(null);
    },
  );

  app.get(
    '/users/me/notification-preferences',
    {
      schema: {
        tags: ['notifications'],
        summary: 'Push preferences per notification category',
        description: 'Toggles control push only; the inbox always records every notification.',
        security,
        response: { 200: notificationPreferencesSchema, 401: errorResponseSchema },
      },
    },
    async (request) => getNotificationPreferences(app.db, request.user.id),
  );

  app.put(
    '/users/me/notification-preferences',
    {
      schema: {
        tags: ['notifications'],
        summary: 'Change push preferences for one or more categories',
        description: 'Categories left out keep their current value. Returns all five.',
        security,
        body: updateNotificationPreferencesSchema,
        response: {
          200: notificationPreferencesSchema,
          400: errorResponseSchema,
          401: errorResponseSchema,
        },
      },
    },
    async (request) =>
      updateNotificationPreferences(app.db, request.user.id, request.body, app.clock()),
  );

  app.post(
    '/users/me/push-devices',
    {
      schema: {
        tags: ['notifications'],
        summary: 'Register or refresh this installation for push',
        description:
          'Upserts the installation with its current token and reactivates it. A token moves to ' +
          'the latest account/installation that registers it.',
        security,
        body: registerDeviceSchema,
        response: {
          204: z.null().describe('Device registered'),
          400: errorResponseSchema,
          401: errorResponseSchema,
        },
      },
    },
    async (request, reply) => {
      await registerPushDevice(app.db, request.user.id, request.body, app.clock());
      return reply.code(204).send(null);
    },
  );

  app.delete(
    '/users/me/push-devices/:installationId',
    {
      schema: {
        tags: ['notifications'],
        summary: 'Stop pushing to one of your installations',
        description: 'Other installations stay active. Unknown installations are a no-op.',
        security,
        params: z.object({ installationId: installationIdSchema }),
        response: {
          204: z.null().describe('Device disabled'),
          400: errorResponseSchema,
          401: errorResponseSchema,
        },
      },
    },
    async (request, reply) => {
      await unregisterPushDevice(
        app.db,
        request.user.id,
        request.params.installationId,
        app.clock(),
      );
      return reply.code(204).send(null);
    },
  );
};
